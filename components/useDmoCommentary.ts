type LocalVoiceModel = {
  generate(
    text: string,
    options?: { voice?: string; speed?: number; priority?: 'high' | 'low' },
  ): Promise<{ audio: Float32Array; sampling_rate: number }>;
  prefetch?: (text: string, options?: { voice?: string; speed?: number }) => void;
  dmoVoiceSource?: 'server' | 'local';
};

type CommentaryPoint = DmoCommentaryPoint & {
  frame: number;
  number: number;
  server: 1 | 2;
  winner: 1 | 2;
  rallyHits: number;
  rallyShotCount?: number;
  highlightReasons?: string;
  inferred?: boolean;
  isTiebreak?: boolean;
  winningStreak?: number;
  scoreBeforeLabel?: string;
  setsWonBefore?: [number, number];
  setsToWin?: number;
  matchOver?: boolean;
  finalSets?: Array<[number, number]>;
};

type CommentaryContext = {
  tour: 'ATP' | 'WTA';
  players: Array<{ name: string; rank: number | null; tourElo: number | null }>;
  headToHead: { firstWins: number; secondWins: number; matches: number } | null;
};

type CommentarySpeaker = 'female' | 'male';
type CommentarySpeech = string | readonly [string, string];
type GeneratedVoiceBuffer =
  | { status: 'ready'; buffer: AudioBuffer }
  | { status: 'cancelled' }
  | { status: 'failed'; phase: string; cause: unknown };

function withVoiceDeadline<T>(work: Promise<T>, milliseconds: number): Promise<T> {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('Commentary voice timed out')), milliseconds);
    work.then(resolve, reject).finally(() => clearTimeout(timer));
  });
}

/** What the player's Commentary button shows. */
export type DmoCommentaryStatus = 'off' | 'starting' | 'on' | 'sign-in' | 'unavailable';

/** Longest a single commentary line may take to prepare before it is skipped. */
const LINE_DEADLINE_MS = 20_000;

function readyVoiceStatus(model: unknown) {
  return (model as { dmoVoiceSource?: string } | null)?.dmoVoiceSource === 'server'
    ? 'Kokoro commentary voices are ready; speech is generated by the WTSL server.'
    : 'Local Kokoro voices are ready; speech is generated on this device.';
}

function isPriorityPointCall(line: string) {
  return /\b(?:break|game|set|match|momentum)\b/i.test(line);
}

type Options = {
  snapshot: Te4LiveSnapshot;
  commentaryNames?: readonly [string, string] | null;
  fullReplay: boolean;
  commentaryPoints?: readonly CommentaryPoint[];
  replayFrame: number;
  tournamentName?: string | null;
  surface: string;
  tournamentRound?: string | null;
  isWta: boolean;
  soundEnabled: boolean;
  soundReady: boolean;
  getAudioContext?: () => AudioContext | null;
  /** A stored replay: its commentary is played from pre-made clips. */
  replayId?: string | null;
  /** A live broadcast: its commentary is played from the broadcast's clips. */
  broadcastId?: string | null;
  playbackState: () => {
    frame: number;
    playing: boolean;
    rallyActive: boolean;
    rallyShotCount?: number;
  };
};

export function useDmoCommentary({
  snapshot,
  commentaryNames,
  fullReplay,
  commentaryPoints = [],
  replayFrame,
  tournamentName,
  surface,
  tournamentRound,
  isWta,
  soundEnabled,
  soundReady,
  getAudioContext,
  replayId = null,
  broadcastId = null,
  playbackState,
}: Options) {
  const [enabled, setEnabled] = useState(false);
  const [error, setError] = useState('');
  const [voiceLoading, setVoiceLoading] = useState(false);
  const [voiceStatus, setVoiceStatus] = useState('');
  const [localVoiceSupported, setLocalVoiceSupported] = useState(false);
  const requestRef = useRef(0);
  const lastRallyCommentaryPointRef = useRef<number | null>(null);
  const rallyCommentedPointsRef = useRef(new Set<number>());
  const recentCommentaryLinesRef = useRef<string[]>([]);
  const snapshotRef = useRef(snapshot);
  snapshotRef.current = snapshot;
  const contextFactsRef = useRef('');
  const enabledRef = useRef(false);
  const soundEnabledRef = useRef(soundEnabled);
  const localModelRef = useRef<LocalVoiceModel | null>(null);
  const localModelPromiseRef = useRef<Promise<LocalVoiceModel | null> | null>(null);
  const localVoiceBackendRef = useRef<'wasm' | 'unknown'>('unknown');
  const localVoiceLoadingRef = useRef(false);
  const localAudioContextRef = useRef<AudioContext | null>(null);
  const localSpeechSessionRef = useRef(0);
  const localSpeechBusyRef = useRef(false);
  const localAudioSourceRef = useRef<AudioBufferSourceNode | null>(null);
  const localSpeechIdleRef = useRef(Promise.resolve());
  const generationFailuresRef = useRef(0);
  const lastStatsPointRef = useRef(0);
  const prefetchedPointsRef = useRef(new Set<number>());
  const lastPointNumberRef = useRef(snapshot.pointCount);
  const lastReplayFrameRef = useRef(replayFrame);
  const pendingTimerRef = useRef<ReturnType<typeof setTimeout> | null>(null);
  const gameCallsRef = useRef<Array<{
    line: CommentarySpeech;
    frame?: number;
    speaker: CommentarySpeaker;
  }>>([]);
  const lastSpeechAtRef = useRef(0);
  const matchKeyRef = useRef('');
  soundEnabledRef.current = soundEnabled && soundReady;

  const names = useMemo(
    () => commentaryNames
      ? [commentaryNames[0].trim(), commentaryNames[1].trim()] as const
      : ['', ''] as const,
    [commentaryNames],
  );
  const hasVerifiedNames = Boolean(names[0] && names[1]);

  /** The point the viewer has reached: replay position, or the live count. */
  const currentPointNumber = useCallback((frame: number) => {
    if (!fullReplay) return snapshotRef.current.pointCount;
    let pointNumber = 0;
    for (const point of commentaryPoints) {
      if (point.frame > frame) break;
      pointNumber = point.number;
    }
    return pointNumber;
  }, [commentaryPoints, fullReplay]);

  /** A full-replay snapshot contains the whole match, so keep future stats hidden. */
  const statsSoFar = useCallback((frame: number) => (fullReplay
    ? summarizeDmoCommentaryStats(commentaryPoints.filter((point) => point.frame <= frame))
    : snapshotRef.current.stats), [commentaryPoints, fullReplay]);

  useEffect(() => {
    const supported = canUseDmoLocalVoice({ allowMobile: true });
    setLocalVoiceSupported(supported);
    if (!supported) {
      setVoiceStatus('Kokoro is unavailable. No device voice will be used.');
    }
  }, []);

  const clearPendingCommentary = useCallback((includeGameCalls = true) => {
    if (pendingTimerRef.current !== null) {
      clearTimeout(pendingTimerRef.current);
      pendingTimerRef.current = null;
    }
    if (includeGameCalls) gameCallsRef.current = [];
  }, []);

  const [kokoroReady, setKokoroReady] = useState(false);
  // Stored replay commentary (pre-made clips) replaces live speech generation.
  const [trackState, setTrackState] = useState<'' | DmoCommentaryTrackState>('');
  const trackPlayerRef = useRef<ReturnType<typeof createDmoCommentaryTrackPlayer<AudioBuffer>> | null>(null);
  // Why commentary cannot be heard, in terms a viewer can act on.
  const [voiceFailure, setVoiceFailure] = useState<'' | 'sign-in' | 'unavailable'>('');
  const voiceFailureRef = useRef<'' | 'sign-in' | 'unavailable'>('');
  const reportVoiceFailure = useCallback((failure: '' | 'sign-in' | 'unavailable') => {
    voiceFailureRef.current = failure;
    setVoiceFailure(failure);
  }, []);

  const prepareLocalAudioContext = useCallback(() => {
    if (typeof window === 'undefined') return null;
    let audioContext = getAudioContext?.() ?? localAudioContextRef.current;
    if (!audioContext || audioContext.state === 'closed') {
      const AudioContextConstructor = window.AudioContext
        ?? (window as Window & { webkitAudioContext?: typeof AudioContext }).webkitAudioContext;
      if (!AudioContextConstructor) return null;
      audioContext = new AudioContextConstructor();
      localAudioContextRef.current = audioContext;
    }
    if (audioContext.state !== 'running') {
      void audioContext.resume().catch(() => {});
      // iPhone Safari can keep Web Audio locked until a sound actually starts
      // inside the tap. Start one silent sample now, while still in the
      // gesture, so commentary generated seconds later is allowed to play.
      try {
        const silence = audioContext.createBufferSource();
        silence.buffer = audioContext.createBuffer(1, 1, 22_050);
        silence.connect(audioContext.destination);
        silence.start(0);
      } catch {
        // Unlocking is best effort; resume() above still applies.
      }
    }
    return audioContext;
  }, [getAudioContext]);

  const ensureLocalVoiceModel = useCallback(() => {
    if (localModelRef.current) return Promise.resolve(localModelRef.current);
    if (localModelPromiseRef.current) return localModelPromiseRef.current;
    // Re-check in the gesture path so an early mobile tap does not lose the
    // Kokoro load while the client-only capability effect is still pending.
    if (!localVoiceSupported && !canUseDmoLocalVoice({ allowMobile: true })) {
      setVoiceStatus('Kokoro is unavailable. No device voice will be used.');
      return Promise.resolve(null);
    }

    localVoiceLoadingRef.current = true;
    localVoiceBackendRef.current = 'unknown';
    setVoiceLoading(true);
    const serverVoice = isMobileDmoLocalVoiceDevice();
    setVoiceStatus(serverVoice
      ? 'Connecting to the WTSL commentary voice.'
      : 'Preparing the commentary voice; local Kokoro loads in the background.');
    // Live broadcasts play stored clips: no speech model on this device.
    const loadVoice = broadcastId
      ? (onProgress: (progress: { status?: string; progress?: number; backend?: string }) => void) => {
        onProgress({ status: 'backend', backend: 'server' });
        return loadDmoLiveClipVoice({
          broadcastId,
          decode: (bytes) => {
            const audioContext = prepareLocalAudioContext();
            if (!audioContext) return Promise.reject(new Error('Web Audio is unavailable'));
            return audioContext.decodeAudioData(bytes);
          },
        });
      }
      : loadDmoLocalVoiceModel;
    const pending = withVoiceDeadline(loadVoice((progress) => {
      if (progress.status === 'backend') {
        localVoiceBackendRef.current = progress.backend === 'wasm' ? 'wasm' : 'unknown';
        setVoiceStatus(progress.backend === 'server'
          ? 'Connecting to the WTSL commentary voice.'
          : 'Preparing local Kokoro on this device.');
      }
      if (progress.status === 'backend-fallback') {
        localVoiceBackendRef.current = progress.backend === 'wasm' ? 'wasm' : 'unknown';
        setVoiceStatus(progress.backend === 'server'
          ? 'The local voice could not start; trying the WTSL commentary voice instead.'
          : 'GPU acceleration could not start; trying local Kokoro on the CPU.');
      }
      if (progress.status === 'warmup') {
        setVoiceStatus('Testing the commentary voice before it starts.');
      }
      if (progress.status === 'progress' && typeof progress.progress === 'number'
        && !localModelRef.current) {
        setVoiceStatus(
          `Loading local voice model: ${Math.round(progress.progress)}% (first use downloads about 92 MB).`,
        );
      }
    // A quantized first-use model is about 92 MB. Slow connections can
    // legitimately need more than 60 seconds; show progress instead of
    // silently timing out before the download can finish.
    }), 300_000)
      .then((model) => {
        localModelRef.current = model;
        if (model) {
          setKokoroReady(true);
          setVoiceStatus(readyVoiceStatus(model));
        } else {
          setKokoroReady(false);
          localVoiceBackendRef.current = 'unknown';
          setVoiceStatus('Local Kokoro voices are unavailable. No device voice was used.');
        }
        return model;
      })
      .catch((cause: unknown) => {
        localModelPromiseRef.current = null;
        setKokoroReady(false);
        reportVoiceFailure((cause as { status?: number } | null)?.status === 401 ? 'sign-in' : 'unavailable');
        setVoiceStatus('Kokoro could not load. No commentary was played.');
        setError('Kokoro could not load. No commentary was played; turn commentary off and on to retry.');
        return null;
      })
      .finally(() => {
        localVoiceLoadingRef.current = false;
        setVoiceLoading(false);
      });
    localModelPromiseRef.current = pending;
    return pending;
  }, [broadcastId, localVoiceSupported, prepareLocalAudioContext, reportVoiceFailure]);

  // While a live broadcast is open, check in every minute: each check lets the
  // server store more of the broadcast's pre-made commentary, so it is ready
  // before play starts. Stops once everything is stored.
  useEffect(() => {
    if (!broadcastId || typeof fetch !== 'function') return;
    let stopped = false;
    let timer: ReturnType<typeof setTimeout> | null = null;
    const checkIn = () => {
      void fetch(`/api/live-dmo/${encodeURIComponent(broadcastId)}/commentary`)
        .then((response) => (response.ok ? response.json() : null))
        .then((body: { complete?: boolean } | null) => {
          if (!stopped && !body?.complete) timer = setTimeout(checkIn, 60_000);
        })
        .catch(() => {
          if (!stopped) timer = setTimeout(checkIn, 60_000);
        });
    };
    checkIn();
    return () => {
      stopped = true;
      if (timer) clearTimeout(timer);
    };
  }, [broadcastId]);

  // The voice is prepared when the viewer turns commentary on, never when the
  // page opens: preparing it downloads a model and uses CPU, which would slow
  // the replay's own loading for viewers who never use commentary. The server
  // voice is usually ready within seconds of the tap.

  const playLocalSpeech = useCallback((
    lines: readonly string[],
    firstSpeaker: CommentarySpeaker,
  ) => {
    const model = localModelRef.current;
    const audioContext = prepareLocalAudioContext();
    if (!model || !audioContext || localSpeechBusyRef.current) return false;

    const session = ++localSpeechSessionRef.current;
    localSpeechBusyRef.current = true;
    let finishSpeech = () => {};
    localSpeechIdleRef.current = new Promise<void>((resolve) => {
      finishSpeech = resolve;
    });
    void (async () => {
      let failurePhase = 'audio resumption';
      try {
        await withVoiceDeadline(audioContext.resume(), 3_000);
        if (audioContext.state !== 'running') throw new Error('Commentary audio is not running');
        const generateBuffer = async (index: number): Promise<GeneratedVoiceBuffer> => {
          const speaker = index === 0
            ? firstSpeaker
            : firstSpeaker === 'female' ? 'male' : 'female';
          const backendSuffix = model.dmoVoiceSource === 'server'
            ? ''
            : localVoiceBackendRef.current === 'wasm' ? ' on the CPU' : '';
          setVoiceStatus(model.dmoVoiceSource === 'server'
            ? 'Generating commentary with the WTSL Kokoro voice.'
            : `Generating commentary locally${backendSuffix}.`);
          let phase = 'local speech generation';
          try {
        // A call that is not ready within the limit is about a point the
        // viewer has already moved past: skip it rather than hold up every
        // later call behind it. Generation runs off the render thread and
        // its result is cached, so nothing is wasted if it finishes late.
            const audio = await withVoiceDeadline(
              model.generate(lines[index], {
                voice: speaker === 'female' ? 'af_heart' : 'am_michael',
                speed: 1.03,
                priority: 'high',
              }),
              LINE_DEADLINE_MS,
            );
            if (session !== localSpeechSessionRef.current || !soundEnabledRef.current) {
              return { status: 'cancelled' };
            }
            if (!audio.audio.length || !(audio.sampling_rate > 0)) {
              throw new Error('Commentary generated no playable audio');
            }
            phase = 'audio output setup';
            const buffer = audioContext.createBuffer(1, audio.audio.length, audio.sampling_rate);
            buffer.copyToChannel(new Float32Array(audio.audio), 0);
            return { status: 'ready', buffer };
          } catch (cause) {
            return { status: 'failed', phase, cause };
          }
        };
        let generated = await generateBuffer(0);
        for (let index = 0; index < lines.length; index += 1) {
          if (generated.status === 'cancelled' || session !== localSpeechSessionRef.current
            || !soundEnabledRef.current) return;
          if (generated.status === 'failed') {
            failurePhase = generated.phase;
            throw generated.cause;
          }
          const buffer = generated.buffer;
          failurePhase = 'audio output setup';
          const source = audioContext.createBufferSource();
          source.buffer = buffer;
          source.connect(audioContext.destination);
          localAudioSourceRef.current = source;
          failurePhase = 'audio playback';
          const playback = withVoiceDeadline(new Promise<void>((resolve) => {
            source.onended = () => {
              if (localAudioSourceRef.current === source) localAudioSourceRef.current = null;
              resolve();
            };
            source.start();
            if (index === 0) {
              recentCommentaryLinesRef.current = [
                ...lines,
                ...recentCommentaryLinesRef.current,
              ].slice(0, 512);
              lastSpeechAtRef.current = Date.now();
            }
          }), Math.ceil(buffer.duration * 1_000 || 0) + 3_000);
          // Prepare the reply while the current fully-buffered audio plays,
          // rather than adding a complete inference delay between speakers.
          const upcoming = index + 1 < lines.length ? generateBuffer(index + 1) : null;
          await playback;
          if (upcoming) generated = await upcoming;
        }
        if (session === localSpeechSessionRef.current && soundEnabledRef.current) {
          generationFailuresRef.current = 0;
          if (voiceFailureRef.current) reportVoiceFailure('');
          setError('');
          setVoiceStatus(readyVoiceStatus(model));
        }
      } catch (cause) {
        if (session === localSpeechSessionRef.current) {
          try { localAudioSourceRef.current?.stop(); } catch { /* Already stopped. */ }
          // A failed line is skipped without unloading Kokoro, so the next
          // queued call can still play. Repeated failures stop this session.
          const generationFailure = failurePhase === 'local speech generation';
          if (generationFailure) generationFailuresRef.current += 1;
          if (!generationFailure || generationFailuresRef.current >= 3) {
            localModelRef.current = null;
            localModelPromiseRef.current = null;
            setKokoroReady(false);
            reportVoiceFailure((cause as { status?: number } | null)?.status === 401 ? 'sign-in' : 'unavailable');
          }
          const detail = (cause instanceof Error
            ? `${cause.name}: ${cause.message}`
            : String(cause))
            .replace(/\s+/g, ' ')
            .slice(0, 120);
          setVoiceStatus(`Kokoro playback failed during ${failurePhase}; no device voice was used.`);
          setError(
            `Kokoro could not play the commentary during ${failurePhase}`
            + `${detail ? `: ${detail}` : ''}. No fallback voice was used.`
            + (localModelRef.current ? ' That line was skipped; commentary continues.' : ''),
          );
        }
      } finally {
        localAudioSourceRef.current = null;
        localSpeechBusyRef.current = false;
        finishSpeech();
      }
    })();

    return true;
  }, [prepareLocalAudioContext, reportVoiceFailure]);

  const speak = useCallback((content: CommentarySpeech, firstSpeaker: CommentarySpeaker = 'female') => {
    const lines = typeof content === 'string' ? [content] : content;
    if (
      lines.some((line) => !line.trim())
      || !soundEnabledRef.current
      || typeof window === 'undefined'
    ) return false;

    if (localModelRef.current) {
      const audioContext = prepareLocalAudioContext();
      if (audioContext) {
        if (playLocalSpeech(lines, firstSpeaker)) return true;
        if (localSpeechBusyRef.current) return false;
      } else {
        setVoiceStatus('Kokoro loaded, but local audio is unavailable.');
      }
    }

    return false;
  }, [playLocalSpeech, prepareLocalAudioContext]);

  const isVoiceBusy = useCallback(() => {
    const synthesis = typeof window !== 'undefined' ? window.speechSynthesis : null;
    return localSpeechBusyRef.current || Boolean(synthesis?.speaking || synthesis?.pending);
  }, []);

  const cancelCommentarySpeech = useCallback(() => {
    localSpeechSessionRef.current += 1;
    const source = localAudioSourceRef.current;
    localAudioSourceRef.current = null;
    if (source) {
      try {
        source.stop();
      } catch {
        // A source that has already ended cannot be stopped again.
      }
    }
    return localSpeechIdleRef.current;
  }, []);

  const stopStoredCommentary = useCallback(() => {
    trackPlayerRef.current?.stop();
    trackPlayerRef.current = null;
    setTrackState('');
  }, []);

  /**
   * Play the replay's stored commentary: the server keeps every line as an
   * MP3, so this only downloads clips a little ahead and plays them on cue.
   * Resolves false if the replay has no stored track, so live voice is used.
   */
  const startStoredCommentary = useCallback(async (request: number, id: string) => {
    try {
      const response = await fetch(`/api/dmo-replays/${encodeURIComponent(id)}/commentary`);
      if (!response.ok) return false;
      const track = await response.json() as {
        fps?: number;
        cues?: Array<{ at: number | null; clip: string; group: number; mustPlay?: boolean; kind?: string }>;
      };
      if (request !== requestRef.current || !enabledRef.current) return true;
      if (!Array.isArray(track.cues) || !track.cues.length) return false;
      const player = createDmoCommentaryTrackPlayer<AudioBuffer>({
        cues: track.cues,
        fps: track.fps,
        loadClip: async (clip) => {
          const audioContext = prepareLocalAudioContext();
          if (!audioContext) throw new Error('Web Audio is unavailable');
          const clipResponse = await fetch(
            `/api/dmo-replays/${encodeURIComponent(id)}/commentary/${clip}`,
          );
          if (!clipResponse.ok) throw new Error(`Commentary clip returned ${clipResponse.status}`);
          return audioContext.decodeAudioData(await clipResponse.arrayBuffer());
        },
        playClip: (buffer) => new Promise<void>((resolve, reject) => {
          const audioContext = prepareLocalAudioContext();
          if (!audioContext) {
            reject(new Error('Web Audio is unavailable'));
            return;
          }
          const source = audioContext.createBufferSource();
          source.buffer = buffer;
          source.connect(audioContext.destination);
          localAudioSourceRef.current = source;
          localSpeechBusyRef.current = true;
          lastSpeechAtRef.current = Date.now();
          source.onended = () => {
            if (localAudioSourceRef.current === source) localAudioSourceRef.current = null;
            localSpeechBusyRef.current = false;
            lastSpeechAtRef.current = Date.now();
            resolve();
          };
          source.start();
        }),
        onState: (state) => {
          if (request !== requestRef.current) return;
          setTrackState(state);
          if (state === 'unavailable') {
            reportVoiceFailure('unavailable');
            setVoiceStatus('Stored commentary clips could not be downloaded.');
          } else if (state === 'on') {
            setVoiceStatus('Playing stored replay commentary.');
          }
        },
      });
      trackPlayerRef.current = player;
      const playback = playbackState();
      player.start(playback.frame, playback.playing);
      return true;
    } catch {
      return false;
    }
  }, [playbackState, prepareLocalAudioContext, reportVoiceFailure]);

  // Stored commentary follows the replay four times a second: cues fire at
  // their frames, and pausing silences the line being spoken.
  const trackActive = trackState !== '';
  useEffect(() => {
    if (!enabled || !trackActive) return;
    const timer = setInterval(() => {
      const player = trackPlayerRef.current;
      if (!player) return;
      const playback = playbackState();
      if (!playback.playing && localAudioSourceRef.current) cancelCommentarySpeech();
      player.update(playback.frame, playback.playing);
    }, 250);
    return () => clearInterval(timer);
  }, [enabled, trackActive, cancelCommentarySpeech, playbackState]);

  useEffect(() => () => trackPlayerRef.current?.stop(), []);

  const scheduleSpeech = useCallback((
    line: CommentarySpeech,
    { delayMs, minimumGapMs, maxWaitMs, pointFrame, minimumQuietMs = 0, firstSpeaker = 'female', mustDeliver = false }: {
      delayMs: number;
      minimumGapMs: number;
      maxWaitMs: number;
      pointFrame?: number;
      minimumQuietMs?: number;
      firstSpeaker?: CommentarySpeaker;
      mustDeliver?: boolean;
    },
  ) => {
    if (!mustDeliver && gameCallsRef.current.length) return;
    clearPendingCommentary(false);
    if (mustDeliver) {
      gameCallsRef.current.push({ line, frame: pointFrame, speaker: firstSpeaker });
      return;
    }
    const queuedAt = Date.now();
    let quietSince: number | null = null;
    const attempt = () => {
      pendingTimerRef.current = null;
      if (!enabledRef.current || !soundEnabledRef.current) return;
      const waited = Date.now() - queuedAt;
      if (waited > maxWaitMs) return;
      const playback = playbackState();
      // Never announce a live result before its recorded end reaches the court.
      if (!playback.playing || (pointFrame !== undefined && playback.frame < pointFrame)) {
        quietSince = null;
        pendingTimerRef.current = setTimeout(attempt, 250);
        return;
      }
      if (playback.rallyActive) {
        quietSince = null;
        // Point reactions describe the completed point and must not vanish
        // just because the next serve has started. Longer facts still wait
        // for a quiet gap.
        if (pointFrame === undefined) {
          pendingTimerRef.current = setTimeout(attempt, 250);
          return;
        }
      }

      quietSince ??= Date.now();
      if (Date.now() - quietSince < minimumQuietMs) {
        pendingTimerRef.current = setTimeout(attempt, 250);
        return;
      }

      const voiceBusy = isVoiceBusy();
      const gapRemaining = minimumGapMs - (Date.now() - lastSpeechAtRef.current);
      if (voiceBusy || gapRemaining > 0) {
        const retryAfter = voiceBusy ? 500 : Math.min(gapRemaining, 1_000);
        if (waited + retryAfter <= maxWaitMs) {
          pendingTimerRef.current = setTimeout(attempt, retryAfter);
        }
        return;
      }
      if (!speak(line, firstSpeaker)) {
        setError('Commentary could not start. Turn commentary off and on to retry.');
      }
    };
    pendingTimerRef.current = setTimeout(attempt, delayMs);
  }, [clearPendingCommentary, isVoiceBusy, speak, playbackState]);

  const toggle = useCallback(() => {
    // Unlock audio synchronously in the user's tap, before cancellation or the
    // first model download crosses an async boundary (especially on iOS).
    // Tapping a button that says commentary is unavailable retries at once,
    // rather than first turning commentary off.
    const retrying = enabledRef.current && voiceFailureRef.current !== '';
    const preparedAudioContext = (!enabledRef.current || retrying) && soundEnabled && soundReady
      ? prepareLocalAudioContext() : null;
    const request = ++requestRef.current;
    contextFactsRef.current = '';
    if (enabledRef.current) {
      enabledRef.current = false;
      setEnabled(false);
      clearPendingCommentary();
      cancelCommentarySpeech();
      lastRallyCommentaryPointRef.current = null;
      rallyCommentedPointsRef.current.clear();
      setError('');
      reportVoiceFailure('');
      stopStoredCommentary();
      if (!retrying) return;
    }
    if (!soundEnabled || !soundReady) {
      setError('Enable broadcast sound first, then turn on commentary.');
      return;
    }
    if (!hasVerifiedNames) {
      setError('Verified WTSL player names are unavailable; character names will not be used.');
      return;
    }
    if (typeof window === 'undefined') {
      setError('Spoken commentary is not supported by this browser.');
      return;
    }
    void cancelCommentarySpeech();
    if (request !== requestRef.current || !soundEnabledRef.current) return;
    const audioContext = preparedAudioContext;
    setError('');
    // Kokoro is the only commentary voice. Download even if Web Audio is
    // unavailable, then report a playback error rather than using another voice.
    const supportsLocalVoice = localVoiceSupported
      || canUseDmoLocalVoice({ allowMobile: true });
    if (!supportsLocalVoice) {
      setVoiceStatus('Kokoro is unavailable in this browser. No commentary was played.');
      setError('Kokoro is required for commentary but is unavailable here.');
      return;
    }

    enabledRef.current = true;
    generationFailuresRef.current = 0;
    lastStatsPointRef.current = currentPointNumber(playbackState().frame);
    prefetchedPointsRef.current.clear();
    setEnabled(true);
    lastRallyCommentaryPointRef.current = null;
    rallyCommentedPointsRef.current.clear();
    clearPendingCommentary();
    lastPointNumberRef.current = Math.max(
      snapshot.pointCount,
      ...snapshot.recentPoints.map((point) => point.number),
    );
    lastReplayFrameRef.current = playbackState().frame;
    const matchKey = names.join('\u0000');
    matchKeyRef.current = matchKey;

    const introduction = buildDmoCommentaryIntroduction({
      names,
      tournament: tournamentName ?? '',
      surface,
      round: tournamentRound ?? '',
    });
    const coHostOpening = buildDmoCommentaryOpeningReply({
      names,
      recentLines: recentCommentaryLinesRef.current,
    });
    const opening: CommentarySpeech = coHostOpening
      ? [introduction, coHostOpening] as const : introduction;
    const startLiveVoice = () => {
      if (localModelRef.current) {
        setKokoroReady(true);
        if (!audioContext || !speak(opening, 'female')) {
          setError('Kokoro could not start audio. No other voice was used.');
          reportVoiceFailure('unavailable');
        }
      } else {
        if (!localVoiceLoadingRef.current) {
          setVoiceStatus('Preparing Kokoro; commentary will start when it is ready.');
        }
        void ensureLocalVoiceModel().then((model) => {
          if (request !== requestRef.current || !enabledRef.current || !soundEnabledRef.current) return;
          const latest = snapshotRef.current;
          lastPointNumberRef.current = Math.max(
            latest.pointCount,
            ...latest.recentPoints.map((point) => point.number),
          );
          lastReplayFrameRef.current = playbackState().frame;
          if (!model) {
            setError('Kokoro could not load. No commentary was played; turn commentary off and on to retry.');
            if (!voiceFailureRef.current) reportVoiceFailure('unavailable');
            return;
          }
          if (!prepareLocalAudioContext() || !speak(opening, 'female')) {
            setError('Kokoro loaded, but could not start audio. No other voice was used.');
            reportVoiceFailure('unavailable');
          }
        });
      }

      const query = new URLSearchParams({
        first: names[0],
        second: names[1],
        tour: isWta ? 'WTA' : 'ATP',
      });
      void fetch(`/api/dmo-commentary/context?${query.toString()}`)
        .then(async (response) => {
          if (!response.ok) throw new Error('WTSL context request failed');
          return response.json() as Promise<{ context?: CommentaryContext | null }>;
        })
        .then(({ context }) => {
          if (!enabledRef.current || requestRef.current !== request || !context) return;
          const facts = buildDmoCommentaryFacts({ names, context });
          const matchFacts = buildDmoMatchCommentary({
            names,
            stats: statsSoFar(playbackState().frame),
          });
          const combinedFacts = [facts, matchFacts].filter(Boolean).join(' ');
          if (!combinedFacts) return;
          // The playback observer delivers this in a later quiet interval.
          // Fetch completion must not overwrite the opening or a point reaction.
          contextFactsRef.current = combinedFacts;
        })
        .catch(() => {
          if (enabledRef.current && requestRef.current === request) setError('WTSL facts are unavailable; point commentary can still continue.');
        });
    };

    // Full replays and broadcasts use server-stored clips only. If a replay
    // has no stored track or the server cannot be reached, report unavailable
    // and let the viewer retry; never generate speech on the device.
    if (fullReplay) {
      if (replayId) {
        setTrackState('starting');
        setVoiceStatus('Loading the stored replay commentary.');
        void startStoredCommentary(request, replayId).then((started) => {
          if (started || request !== requestRef.current || !enabledRef.current) return;
          setTrackState('unavailable');
          reportVoiceFailure('unavailable');
          setVoiceStatus('Stored replay commentary is unavailable; turn it off and on to retry.');
        });
      } else if (broadcastId) {
        startLiveVoice();
      } else {
        setTrackState('unavailable');
        reportVoiceFailure('unavailable');
        setVoiceStatus('Stored commentary is unavailable for this replay.');
      }
      return;
    }
    startLiveVoice();
  }, [
    clearPendingCommentary,
    cancelCommentarySpeech,
    ensureLocalVoiceModel,
    localVoiceSupported,
    isWta,
    names,
    prepareLocalAudioContext,
    reportVoiceFailure,
    playbackState,
    replayFrame,
    fullReplay,
    replayId,
    startStoredCommentary,
    stopStoredCommentary,
    soundEnabled,
    soundReady,
    hasVerifiedNames,
    currentPointNumber,
    statsSoFar,
    snapshot.pointCount,
    snapshot.recentPoints,
    snapshotRef,
    surface,
    speak,
    kokoroReady,
    tournamentName,
    tournamentRound,
  ]);

  useEffect(() => {
    enabledRef.current = enabled;
    if (!enabled) clearPendingCommentary();
  }, [clearPendingCommentary, enabled]);

  useEffect(() => {
    if (soundEnabled && soundReady) return;
    requestRef.current += 1;
    contextFactsRef.current = '';
    enabledRef.current = false;
    setEnabled(false);
    clearPendingCommentary();
    cancelCommentarySpeech();
    setError('');
  }, [cancelCommentarySpeech, clearPendingCommentary, soundEnabled, soundReady]);

  useEffect(() => {
    const matchKey = names.join('\u0000');
    if (matchKeyRef.current === matchKey) return;
    requestRef.current += 1;
    contextFactsRef.current = '';
    matchKeyRef.current = matchKey;
    lastPointNumberRef.current = snapshot.pointCount;
    recentCommentaryLinesRef.current = [];
    lastReplayFrameRef.current = replayFrame;
    rallyCommentedPointsRef.current.clear();
    clearPendingCommentary();
    cancelCommentarySpeech();
    enabledRef.current = false;
    setEnabled(false);
  }, [cancelCommentarySpeech, clearPendingCommentary, names, replayFrame]);

  useEffect(() => {
    if (!enabled || !kokoroReady) return;
    const timer = setInterval(() => {
      const playback = playbackState();
      // Pause stops speech, but a call that has already begun may finish when
      // the next rally starts. Otherwise ordinary gaps cut every sentence off.
      if (!playback.playing) {
        cancelCommentarySpeech();
        lastRallyCommentaryPointRef.current = null;
        return;
      }

      const gameCall = gameCallsRef.current[0];
      if (gameCall) {
        if ((gameCall.frame === undefined || playback.frame >= gameCall.frame)
          && !isVoiceBusy() && Date.now() - lastSpeechAtRef.current >= 500
          && speak(gameCall.line, gameCall.speaker)) {
          gameCallsRef.current.shift();
        }
        return;
      }

      if (!playback.rallyActive) {
        lastRallyCommentaryPointRef.current = null;
      } else {
        const pointNumber = currentPointNumber(playback.frame);
        const minimumGapMs = pointNumber <= 8 ? 8_000 : 10_000;
        const voiceBusy = isVoiceBusy();
        if (
          (playback.rallyShotCount ?? 0) >= 8
          && lastRallyCommentaryPointRef.current !== pointNumber
          && pendingTimerRef.current === null
          && !voiceBusy
          && Date.now() - lastSpeechAtRef.current >= minimumGapMs
        ) {
          const line = buildDmoRallyCommentary({
            names,
            rallyShotCount: playback.rallyShotCount ?? 0,
            pointNumber,
            recentLines: recentCommentaryLinesRef.current,
          });
          if (line) {
            const speaker = pointNumber % 2 === 0 ? 'male' : 'female';
            if (!speak(line, speaker)) {
              setError('Commentary could not start. Turn commentary off and on to retry.');
            } else {
              rallyCommentedPointsRef.current.add(pointNumber);
              if (rallyCommentedPointsRef.current.size > 12) {
                const oldest = rallyCommentedPointsRef.current.values().next().value;
                if (oldest !== undefined) rallyCommentedPointsRef.current.delete(oldest);
              }
            }
            lastRallyCommentaryPointRef.current = pointNumber;
          }
        }
      }

      if (!playback.rallyActive && contextFactsRef.current && pendingTimerRef.current === null
        && !isVoiceBusy() && Date.now() - lastSpeechAtRef.current >= 12_000) {
        const facts = contextFactsRef.current;
        contextFactsRef.current = '';
        scheduleSpeech(facts, {
          delayMs: 0,
          minimumGapMs: 12_000,
          minimumQuietMs: 3_000,
          maxWaitMs: 15_000,
        });
      } else if (!playback.rallyActive && !contextFactsRef.current && pendingTimerRef.current === null
        && !isVoiceBusy() && Date.now() - lastSpeechAtRef.current >= 15_000) {
        // Every 30 points, use only the statistics available at this replay frame.
        const pointNumber = currentPointNumber(playback.frame);
        if (pointNumber < lastStatsPointRef.current) lastStatsPointRef.current = pointNumber;
        if (pointNumber - lastStatsPointRef.current >= 30) {
          lastStatsPointRef.current = pointNumber;
          const line = buildDmoMatchCommentary({ names, stats: statsSoFar(playback.frame) });
          if (line && !recentCommentaryLinesRef.current.includes(line)) {
            scheduleSpeech(line, {
              delayMs: 0,
              minimumGapMs: 15_000,
              minimumQuietMs: 3_000,
              maxWaitMs: 12_000,
              firstSpeaker: pointNumber % 2 === 0 ? 'female' : 'male',
            });
          }
        }
      }
    }, 200);
    return () => clearInterval(timer);
  }, [
    enabled,
    kokoroReady,
    playbackState,
    isVoiceBusy,
    cancelCommentarySpeech,
    scheduleSpeech,
    commentaryPoints,
    fullReplay,
    names,
    snapshot.pointCount,
    speak,
    currentPointNumber,
    statsSoFar,
  ]);

  useEffect(() => {
    if (!enabled || !kokoroReady) return;
    /** What the booth would say about this point, given what has been said so far. */
    const planPointSpeech = (
      point: DmoCommentaryPoint,
      history: readonly DmoCommentaryPoint[],
      suppressRallyCommentary: boolean,
    ) => {
      const pointNumber = point.number ?? 0;
      const enriched = withDmoCommentaryHistory({ ...point, suppressRallyCommentary }, history);
      const mustDeliver = isDmoGameEnding(enriched);
      const recentLines = recentCommentaryLinesRef.current;
      const line = buildDmoPointCommentary(enriched, names, recentLines);
      if (!line) return null;
      // Keep game wrap-ups concise, with a score reply after a set or match.
      // Break, set, and match-point calls stand alone before the next serve.
      const reply = mustDeliver
        ? buildDmoCommentaryScoreReply({ names, point: enriched, recentLines })
        : dmoPressureAfterPoint(enriched)
          ? ''
          : buildDmoCommentaryFollowUp({ names, point: enriched, leadLine: line, recentLines });
      const firstSpeaker: CommentarySpeaker = pointNumber % 2 === 0 ? 'male' : 'female';
      return { pointNumber, line, reply, mustDeliver, firstSpeaker };
    };
    const submitPoint = (point: DmoCommentaryPoint, history: readonly DmoCommentaryPoint[]) => {
      const plan = planPointSpeech(
        point,
        history,
        rallyCommentedPointsRef.current.delete(point.number ?? 0),
      );
      if (!plan) return;
      const { pointNumber, line, reply, mustDeliver, firstSpeaker } = plan;
      const priorityCall = isPriorityPointCall(line);
      scheduleSpeech(reply ? [line, reply] as const : line, {
        delayMs: 250,
        minimumGapMs: priorityCall ? 2_000 : pointNumber <= 8 ? 8_000 : 10_000,
        maxWaitMs: priorityCall ? 8_000 : 9_000,
        pointFrame: point.frame,
        firstSpeaker,
        mustDeliver,
      });
    };
    /**
     * Replays know what comes next: prepare the next point's call while the
     * current one plays, so it can be heard the moment that point ends. If
     * the call changes by then (another line was spoken in between), the new
     * line is prepared as usual.
     */
    const prefetchNextPoint = () => {
      const model = localModelRef.current;
      if (!model?.prefetch) return;
      const upcoming = commentaryPoints.find((point) => point.frame > lastReplayFrameRef.current);
      if (!upcoming || prefetchedPointsRef.current.has(upcoming.number ?? -1)) return;
      prefetchedPointsRef.current.add(upcoming.number ?? -1);
      const plan = planPointSpeech(
        upcoming,
        commentaryPoints,
        rallyCommentedPointsRef.current.has(upcoming.number ?? 0),
      );
      if (!plan) return;
      const voiceFor = (speaker: CommentarySpeaker) => (speaker === 'female' ? 'af_heart' : 'am_michael');
      model.prefetch(plan.line, { voice: voiceFor(plan.firstSpeaker), speed: 1.03 });
      if (plan.reply) {
        model.prefetch(plan.reply, {
          voice: voiceFor(plan.firstSpeaker === 'female' ? 'male' : 'female'),
          speed: 1.03,
        });
      }
    };
    if (fullReplay) {
      const previousFrame = lastReplayFrameRef.current;
      if (replayFrame < previousFrame) {
        lastReplayFrameRef.current = replayFrame;
        lastStatsPointRef.current = currentPointNumber(replayFrame);
        rallyCommentedPointsRef.current.clear();
        prefetchedPointsRef.current.clear();
        clearPendingCommentary();
        cancelCommentarySpeech();
        return;
      }
      const duePoints = commentaryPoints.filter(
        (point) => point.frame > previousFrame && point.frame <= replayFrame,
      );
      lastReplayFrameRef.current = replayFrame;
      const gamePoints = duePoints.filter(isDmoGameEnding);
      for (const point of gamePoints.length ? gamePoints : duePoints.slice(-1)) {
        submitPoint(point, commentaryPoints);
      }
      prefetchNextPoint();
      return;
    }

    const lastSeen = lastPointNumberRef.current;
    const live = snapshotRef.current;
    const enrichedHistory = snapshot.recentPoints.map((point) => {
      const previousPoint = snapshot.recentPoints.find(
        (candidate) => candidate.number === point.number - 1,
      );
      return {
        ...point,
        scoreBeforeLabel: previousPoint?.scoreLabel,
        scoreAfterLabel: point.scoreLabel,
        setBefore: previousPoint?.setNumber,
        setAfter: point.setNumber,
      };
    });
    const newPoints = enrichedHistory.filter((point) => point.number > lastSeen);
    if (!newPoints.length) return;
    lastPointNumberRef.current = newPoints.at(-1)!.number;
    // The completed sets describe the latest point only. Don't infer a later
    // set or match result for an earlier point in this update batch.
    const setsToWin = live.bestOf === 1 || live.bestOf === 3 || live.bestOf === 5
      ? Math.ceil(live.bestOf / 2) : undefined;
    const completedSets = Array.isArray(live.score?.sets) ? live.score.sets : null;
    const enrichedPoints = newPoints.map((point): CommentaryPoint => {
      if (point.number !== live.pointCount || !completedSets || !setsToWin) return point as CommentaryPoint;
      const after: [number, number] = [0, 0];
      for (const [first, second] of completedSets) {
        if (first !== second) after[first > second ? 0 : 1] += 1;
      }
      const setEnded = Number.isInteger(point.setBefore) && Number.isInteger(point.setAfter)
        && point.setAfter === point.setBefore! + 1;
      const before: [number, number] = [...after];
      if (setEnded) before[point.winner - 1] -= 1;
      if (before[0] < 0 || before[1] < 0) return point as CommentaryPoint;
      const matchOver = setEnded && after[point.winner - 1] === setsToWin;
      return {
        ...point,
        setsWonBefore: before,
        setsToWin,
        ...(matchOver
          ? { matchOver: true, finalSets: completedSets.map(([a, b]) => [a, b] as [number, number]) }
          : {}),
      } as CommentaryPoint;
    });
    const gamePoints = enrichedPoints.filter(isDmoGameEnding);
    for (const point of gamePoints.length ? gamePoints : enrichedPoints.slice(-1)) {
      submitPoint(point, enrichedHistory as DmoCommentaryPoint[]);
    }
  }, [
    commentaryPoints,
    enabled,
    kokoroReady,
    fullReplay,
    names,
    replayFrame,
    scheduleSpeech,
    cancelCommentarySpeech,
    currentPointNumber,
    snapshot.recentPoints,
  ]);

  useEffect(() => () => {
    requestRef.current += 1;
    clearPendingCommentary();
    cancelCommentarySpeech();
  }, [cancelCommentarySpeech, clearPendingCommentary]);

  // A plain state for the player's button: never silently broken.
  const status: DmoCommentaryStatus = !enabled
    ? 'off'
    : voiceFailure || ((trackState ? trackState === 'on' : kokoroReady) ? 'on' : 'starting');

  return {
    enabled, error, voiceLoading, voiceStatus, toggle, status,
    localVoiceSupported,
  };
}
